"""Generate the Markdown data notes and model card from the actual run."""

from __future__ import annotations

from pathlib import Path

from . import config


def _n(x: int) -> str:
    return f"{x:,}"


def write_data_notes(prof: dict, split: dict, genres: dict, path: Path) -> None:
    r = prof["rules"]
    conflicts = ", ".join(f"{k}: {v}" for k, v in r["ids_with_conflicting_values"].items() if v) or "none"
    missing = ", ".join(f"{k} ({v})" for k, v in prof["missing_values"].items()) or "none"
    ranges = "\n".join(
        f"| {k} | {v['min']:g} | {v['max']:g} | {v['mean']:g} |" for k, v in prof["feature_ranges_rows"].items()
    )
    text = f"""# Data notes

_Generated by `pipeline/build.py` from the supplied CSV (sha256 prefix in `web/public/data/meta.json`)._

## What the file contains

| Check | Value |
| --- | --- |
| Rows | {_n(prof['rows'])} |
| Unique `track_id` values | {_n(prof['unique_track_ids'])} |
| Genres (`track_genre`) | {prof['genres']} |
| Missing values | {missing} |
| IDs that appear on more than one row | {_n(prof['ids_on_multiple_rows'])} (max {prof['max_rows_per_id']} rows for one ID) |
| Exact repeats of a track–genre pair | {_n(r['repeated_track_genre_pairs_dropped'])} |
| Unique track–genre memberships | {_n(prof['memberships'])} |
| Tracks listed under more than one genre | {_n(prof['tracks_in_multiple_genres'])} (max {prof['max_genres_per_track']} genres) |
| IDs whose rows disagree | {conflicts} |
| Popularity = 0 (rows / canonical tracks / memberships) | {_n(prof['zero_popularity_rows'])} / {_n(prof['zero_popularity_tracks'])} / {_n(prof['zero_popularity_memberships'])} |
| Tracks with tempo = 0 / time signature = 0 | {prof['tempo_zero_tracks']} / {prof['time_signature_zero_tracks']} |

Row-level feature ranges:

| Column | Min | Max | Mean |
| --- | --- | --- | --- |
{ranges}

## Canonicalisation rules

1. Exact repeats of a (track_id, track_genre) pair are dropped, keeping the lowest original row index ({_n(r['repeated_track_genre_pairs_dropped'])} rows).
2. The remaining rows are split into two tables: a **canonical track table** (one row per `track_id`, {_n(prof['unique_track_ids'])} rows) and a **track-to-genre mapping** ({_n(prof['memberships'])} memberships). Every genre membership is kept.
3. Artist, album, title, duration, explicit flag and all audio features agree across the rows of every ID in this file. If they ever disagree, the lowest row index wins.
4. Popularity disagrees for {_n(r['popularity_conflict_ids'])} IDs (largest spread {r['popularity_conflict_max_spread']} points; {r['popularity_conflict_ids_with_a_zero_row']} of them have a zero on at least one row). The canonical score is the **median of that ID's per-genre rows, rounded half up**. This rule is deterministic and does not depend on row order.
5. Zero popularity is a valid value and is kept everywhere. It is shown as its own bucket in every histogram.
6. {_n(r['model_invalid_tracks'])} track fails the domain validation rules (0 ms duration; it is also the only row with missing artist, album and title). It stays in the descriptive counts but is excluded from modelling and similarity search.

## Denominators used on the site

* **Unique tracks**: headline cards, the popularity histogram and the Track Explorer. A track that belongs to several selected genres is counted once.
* **Track–genre memberships**: the genre comparison chart, the genre feature comparison and the genre explorer. Each genre counts its own tracks, so a track in two genres contributes to both genres' statistics.

## Duplicate recordings

The same song often appears under several IDs (single, album, compilation). IDs are linked into one *duplicate-recording group* when their normalised artist string and normalised title both match, or when all nine audio features plus duration match exactly. {_n(prof['duplicate_recording_groups'])} groups cover {_n(prof['tracks_in_duplicate_recording_groups'])} tracks. Groups never cross the model's train/validation/test split. Of the {_n(prof['zero_popularity_tracks'])} zero-score tracks, {_n(prof['zero_tracks_in_duplicate_groups'])} belong to a duplicate-recording group and {_n(prof['zero_tracks_with_nonzero_duplicate'])} have a sibling ID with a non-zero score.

What can still overlap: re-recordings or remasters whose titles differ (for example "- Remastered 2011"), covers by other artists, and versions with different featured-artist credits. In the test split, {_n(split['testTracksWithTitleInTrain'])} tracks share a normalised title with some training track regardless of artist credit. A matching title alone is weak evidence of a shared recording.

## Sampling and snapshot limitations

* The file has roughly 1,000 rows per genre label. Genre sizes are a sampling decision, not a measure of how common a genre is, and the sample is not a random draw from any catalogue.
* Popularity is a single snapshot score supplied with the file. The file has no collection date, release date, play counts or listener data, so the site makes no claims about trends over time, listening behaviour or why a track is popular.
* Genre labels come from the collection process and overlap heavily (for example `songwriter` and `singer-songwriter`).
* All comparisons are descriptive associations within this sample. None of them are causal.

## Publication and redistribution

The CSV matches a widely mirrored "Spotify Tracks Dataset" compilation. Its mirrors list different licences (BSD on Hugging Face, CC0 on a Kaggle mirror), and the underlying data was obtained from Spotify, whose Developer Terms and Developer Policy restrict redistribution of Spotify content and its use for training machine-learning models. Because permission to republish track-level records could not be established, the public site is **aggregate-only**:

* Published: genre-level statistics, counts per (genre combination, popularity score, 5-second duration bin), scaler parameters, model parameters, held-out metrics and synthetic test fixtures.
* Not published: the raw CSV, track IDs, titles, artists, albums or per-track feature vectors. These exist only in the git-ignored `data/raw/` and `web/local-data/` folders, used by the local full-data mode.
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_model_card(ev: dict, spec: dict, split: dict, prof: dict, path: Path) -> None:
    t, b = ev["test"], ev["baselineTest"]
    comp = "\n".join(
        f"| {c['label']}{' **(selected)**' if c['selected'] else ''} | {c['validation']['mae']:.2f} | {c['test']['mae']:.2f} | {c['test']['rmse']:.2f} | {c['test']['r2']:.3f} |"
        for c in ev["comparison"]
    )
    def score(value):
        return "—" if value is None else f"{value:.1f}"

    bands = "\n".join(
        f"| {r['band']} | {_n(r['n'])} | {score(r['mae'])} | {score(r['baselineMae'])} | {score(r['meanPredicted'])} | {score(r['signedError'])} |" for r in ev["bands"]
    )
    imp = "\n".join(f"| {r['feature']} | {r['maeIncrease']:.3f} | {r['std']:.3f} |" for r in ev["importance"]["rows"])
    rows = split["rows"]
    gain = ev["maeGain"]
    low, high = gain["interval95"]
    nonzero = ev["nonzero"]
    text = f"""# Model card: popularity estimate from audio features

_Generated by `pipeline/build.py`. Every number below comes from the last training run._

**Task.** Regress the 0–100 `popularity` snapshot score in the CSV from audio features only.

**Predictors ({len(spec['features'])}, in export order).** {", ".join(f"`{f}`" for f in spec['features'])}.
Excluded: track ID, title, artist and album text, genre, and anything derived from popularity.

**Data.** {_n(sum(rows.values()))} model-valid canonical tracks (one row per `track_id`; {split['excludedInvalidTracks']} track with 0 ms duration excluded). Split {split['method']} with seed {split['seed']}: train {_n(rows['train'])}, validation {_n(rows['validation'])}, test {_n(rows['test'])}. No duplicate-recording group spans two splits (see `docs/data-notes.md` for how groups are formed and what overlap can remain).

**Preprocessing.** Fitted on the training split only. The linear model z-scores numeric features using training means and standard deviations and one-hot encodes `key` and `time_signature` with training-set levels. The tree model uses raw feature values.

**Selection.** {ev['selectionRule']}. The test split was used only for the final numbers below.

## Results on the held-out test split ({_n(ev['testRows'])} tracks)

| Model | Validation MAE | Test MAE | Test RMSE | Test R² |
| --- | --- | --- | --- | --- |
{comp}

Selected model: **{ev['selected']}**. The baseline always predicts {ev['baselineValue']:g}, the training-split median. Test MAE {t['mae']:.2f} vs {b['mae']:.2f} for the median baseline ({gain['points']:+.2f} points of MAE improvement, paired 95% recording-group bootstrap interval [{low:.2f}, {high:.2f}]). Test R² {t['r2']:.3f}.

On the {_n(nonzero['n'])} nonzero-score test tracks, MAE is {nonzero['mae']:.2f} versus {nonzero['baselineMae']:.2f} for the baseline, using the same fitted models.

### Error by observed popularity band

| Observed popularity | Tracks | Model MAE | Baseline MAE | Mean prediction | Predicted − observed |
| --- | --- | --- | --- | --- | --- |
{bands}

### Permutation importance (test split)

{ev['importance']['method']}. It describes how much the model's predictions rely on each feature, not what causes popularity.

| Feature | MAE increase | Std |
| --- | --- | --- |
{imp}

## Input validation and output

Inputs outside these inclusive bounds are rejected, both in evaluation and in the browser: {", ".join(f"{k} {v['min']}–{v['max']}{' (integer)' if v['integer'] else ''}" for k, v in spec['validation'].items())}. Predictions are clipped to {spec['clip'][0]:g}–{spec['clip'][1]:g}, and the reported metrics use clipped predictions.

## Export and parity

The selected model is exported to `web/public/data/model.json` with its feature order, validation rules and parameters ({spec['kind']} format). `pipeline/tests/test_modeling.py` checks the exported JSON against scikit-learn, and `web/src/lib/model.test.ts` checks the TypeScript implementation against the same fixtures (synthetic inputs, bound edges and values placed exactly on split thresholds), with tolerance 1e-9.

## Limitations

* Audio features explain only a small share of the variation in this score. Popularity also depends on things the CSV does not contain: artist audience, promotion, playlist placement, release timing and market.
* The score is one snapshot from the collection process, and the sample has about 1,000 rows per genre label rather than a representative catalogue.
* Errors are largest for tracks with zero or very high observed popularity, as the band table shows.
* The estimate describes this dataset only. It is not a forecast of real-world success.
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
